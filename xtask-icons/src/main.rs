//! Standalone codegen: `assets/icons/symbols/*.svg` -> `hodo-icons/src/paths.rs`.
//! Run: `cargo run --manifest-path xtask-icons/Cargo.toml`
//!
//! Offline only. Each vendored Material Symbols Outlined SVG is parsed once by
//! `usvg`, its single `<path>` is mapped from the 960-unit viewBox onto the
//! 24x24 canvas via the node's absolute transform, and the resulting
//! absolute-only segments are emitted as a normalized path-d string.
//! Nothing here runs at hodo runtime.

use std::fs;
use std::path::{Path, PathBuf};

use usvg::tiny_skia_path::{PathSegment, Point};

const STAMP: &str = "// GENERATED by xtask-icons from assets/icons/symbols/*.svg — do not edit.";

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask-icons lives at the workspace root")
        .to_path_buf()
}

/// Deterministic number rendering: 4 decimal places, no trailing zeros, no
/// negative zero. Coordinates come from a 960 -> 24 scale (1/40), so this is
/// well below the visible precision of a 24px icon.
fn num(v: f32) -> String {
    if v.abs() < 0.000_05 {
        return "0".to_string();
    }
    let s = format!("{v:.4}");
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s == "-0" {
        "0".to_string()
    } else {
        s.to_string()
    }
}

fn mapped(p: Point, ts: &usvg::Transform) -> Point {
    let mut p = p;
    ts.map_point(&mut p);
    p
}

/// Depth-first search for the first path node. The vendored symbols have
/// exactly one `<path>` (verified at vendoring time); groups, if any, are
/// traversed so a future wrapper group cannot break codegen silently.
fn first_path(root: &usvg::Group) -> Option<(&usvg::Path, usvg::Transform)> {
    for node in root.children() {
        match node {
            usvg::Node::Path(p) => return Some((p, p.abs_transform())),
            usvg::Node::Group(g) => {
                if let Some(found) = first_path(g) {
                    return Some(found);
                }
            }
            _ => {}
        }
    }
    None
}

/// Provenance notes that are hand-written into the generated file for these
/// icons. Codegen reproduces them so the roundtrip check stays byte-exact.
fn arm_comment(name: &str) -> &'static str {
    match name {
        "star" => concat!(
            "        // `star`: the vendored Material Symbols Outlined glyph — outer 5-point\n",
            "        // contour plus the small inner fill-star (opposite winding = hole).\n",
        ),
        "star_border" => concat!(
            "        // `star_border`: outline-only variant. The vendored star_border.svg is a\n",
            "        // byte-identical copy of star.svg (see SOURCES.md), so the outline data\n",
            "        // is not recoverable locally; derived from the 5-point outline commands\n",
            "        // of the filled star as an outer contour + counter-wound inner contour\n",
            "        // (a hollow ring), with no inner fill-star path.\n",
        ),
        _ => "",
    }
}

/// Parse one SVG and return its normalized, absolute-only path-d string.
fn normalize(svg: &[u8], name: &str) -> Result<String, String> {
    let tree = usvg::Tree::from_data(svg, &usvg::Options::default())
        .map_err(|e| format!("{name}: usvg parse: {e}"))?;
    let (path, ts) = first_path(tree.root()).ok_or_else(|| format!("{name}: no <path> node"))?;

    let mut out = String::new();
    for seg in path.data().segments() {
        match seg {
            PathSegment::MoveTo(p) => {
                let p = mapped(p, &ts);
                out.push_str(&format!("M{} {} ", num(p.x), num(p.y)));
            }
            PathSegment::LineTo(p) => {
                let p = mapped(p, &ts);
                out.push_str(&format!("L{} {} ", num(p.x), num(p.y)));
            }
            PathSegment::QuadTo(c, p) => {
                let (c, p) = (mapped(c, &ts), mapped(p, &ts));
                out.push_str(&format!(
                    "Q{} {} {} {} ",
                    num(c.x),
                    num(c.y),
                    num(p.x),
                    num(p.y)
                ));
            }
            PathSegment::CubicTo(c1, c2, p) => {
                let (c1, c2, p) = (mapped(c1, &ts), mapped(c2, &ts), mapped(p, &ts));
                out.push_str(&format!(
                    "C{} {} {} {} {} {} ",
                    num(c1.x),
                    num(c1.y),
                    num(c2.x),
                    num(c2.y),
                    num(p.x),
                    num(p.y)
                ));
            }
            PathSegment::Close => out.push_str("Z "),
        }
    }

    let out = out.trim().to_owned();
    if out.is_empty() {
        return Err(format!("{name}: empty path"));
    }
    // Guard against a change in upstream viewBox conventions: every emitted
    // coordinate must land on the 24x24 canvas.
    for tok in out.split_whitespace() {
        // Command-prefixed tokens (e.g. "M7.825") simply fail to parse.
        if let Ok(v) = tok.parse::<f32>() {
            if !(-0.01..=24.01).contains(&v) {
                return Err(format!(
                    "{name}: coordinate {v} outside 24x24 canvas — viewBox convention changed?"
                ));
            }
        }
    }
    Ok(out)
}

fn generate(root: &Path) -> Result<String, String> {
    let dir = root.join("assets/icons/symbols");
    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .map_err(|e| format!("read {}: {e}", dir.display()))?
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("svg"))
        .collect();
    files.sort(); // deterministic independent of filesystem order

    let mut names = Vec::new();
    let mut arms = Vec::new();
    for file in &files {
        let name = file
            .file_stem()
            .and_then(|s| s.to_str())
            .ok_or_else(|| format!("bad filename {}", file.display()))?
            .to_owned();
        let svg = fs::read(file).map_err(|e| format!("read {}: {e}", file.display()))?;
        let d = normalize(&svg, &name)?;
        arms.push(format!(
            "{}        \"{name}\" => Some(\"{d}\"),\n",
            arm_comment(&name)
        ));
        names.push(format!("    \"{name}\",\n"));
    }

    let mut out = String::new();
    out.push_str(STAMP);
    out.push('\n');
    out.push_str(
        "// Source: google/material-design-icons, Material Symbols Outlined 24px (Apache-2.0).\n",
    );
    out.push('\n');
    out.push_str("/// Every vendored icon name, sorted lexicographically.\n");
    out.push_str("pub const ICON_NAMES: &[&str] = &[\n");
    for n in &names {
        out.push_str(n);
    }
    out.push_str("];\n\n");
    out.push_str("/// Absolute-only path data on a 24x24 canvas, or `None` for an unknown name.\n");
    out.push_str("///\n");
    out.push_str("/// Command alphabet: `M x y`, `L x y`, `Q cx cy x y`,\n");
    out.push_str("/// `C c1x c1y c2x c2y x y`, `Z`. No relative commands, no arcs.\n");
    out.push_str("pub fn icon_path(name: &str) -> Option<&'static str> {\n");
    out.push_str("    match name {\n");
    for arm in &arms {
        out.push_str(arm);
    }
    out.push_str("        _ => None,\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    Ok(out)
}

fn write_generated(root: &Path) -> Result<PathBuf, String> {
    let out = generate(root)?;
    let path = root.join("crates/hodo-icons/src/paths.rs");
    fs::create_dir_all(path.parent().expect("paths.rs has a parent"))
        .map_err(|e| format!("create {}: {e}", path.display()))?;
    fs::write(&path, out).map_err(|e| format!("write {}: {e}", path.display()))?;
    Ok(path)
}

fn main() {
    let root = workspace_root();
    let path = write_generated(&root).expect("generate paths.rs");
    println!("generated {}", path.display());
    println!("icons={}", crate_icon_count(&root));
}

fn crate_icon_count(root: &Path) -> usize {
    fs::read_dir(root.join("assets/icons/symbols"))
        .expect("read symbols dir")
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().and_then(|s| s.to_str()) == Some("svg"))
        .count()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roundtrip_matches_checked_in_file() {
        let root = workspace_root();
        let generated = generate(&root).expect("generate");
        let checked_in = fs::read_to_string(root.join("crates/hodo-icons/src/paths.rs"))
            .expect("paths.rs must be checked in");
        assert_eq!(
            checked_in, generated,
            "paths.rs is stale; rerun xtask-icons"
        );
    }

    #[test]
    fn generation_is_deterministic() {
        let root = workspace_root();
        assert_eq!(generate(&root).unwrap(), generate(&root).unwrap());
    }

    #[test]
    fn every_vendored_svg_becomes_one_arm() {
        let root = workspace_root();
        let out = generate(&root).unwrap();
        let arms = out.matches(" => Some(\"").count();
        assert_eq!(arms, crate_icon_count(&root));
        assert_eq!(arms, 41);
    }
}
